import { defineArrayMember, defineField, defineType } from 'sanity';
import { reviewFields } from '../shared/review-fields';
import { CogIcon } from '@sanity/icons/Cog';

export const siteSettings = defineType({
  name: 'siteSettings',
  type: 'document',
  icon: CogIcon,
  groups: [
    { name: 'identity', title: 'Identity', default: true },
    { name: 'hero', title: 'Hero' },
    { name: 'availability', title: 'Availability' },
    { name: 'contact', title: 'Contact & links' },
    { name: 'seo', title: 'Default SEO' },
  ],
  fields: [
    ...reviewFields('identity'),
    defineField({
      name: 'name',
      type: 'string',
      group: 'identity',
      description: 'Your name as shown in the header and hero.',
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'resumeName',
      title: 'Name on résumé',
      type: 'string',
      group: 'identity',
      description: 'Full legal name if it differs from the site name.',
    }),
    defineField({
      name: 'location',
      type: 'string',
      group: 'identity',
      description: 'e.g. "Mumbai, India".',
    }),
    defineField({
      name: 'footerTagline',
      type: 'string',
      group: 'identity',
      description: 'One line under your name in the footer.',
    }),
    defineField({
      name: 'resumeHeadline',
      title: 'Résumé headline',
      type: 'string',
      group: 'identity',
      description:
        'Line under your name on the Résumé page, e.g. "Software Engineer — DevOps & Cloud".',
    }),
    defineField({
      name: 'resumeSummary',
      title: 'Résumé summary',
      type: 'text',
      rows: 3,
      group: 'identity',
      description: 'The Summary paragraph on the Résumé page.',
    }),
    defineField({
      name: 'headlineLabel',
      type: 'string',
      group: 'hero',
      description: 'Small label above the hero.',
      initialValue: 'DevOps · Cloud · Automation',
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'heroLine',
      type: 'string',
      group: 'hero',
      description: 'The big statement under your name.',
      initialValue: 'I automate how software ships and runs.',
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'heroParagraph',
      type: 'text',
      rows: 3,
      group: 'hero',
      description: 'Optional. A short paragraph under the hero line.',
    }),
    defineField({
      name: 'summaryCells',
      type: 'array',
      group: 'hero',
      description: 'Facts strip under the hero, e.g. "Targeting", "Now". Up to 4.',
      of: [defineArrayMember({ type: 'labelledValue' })],
      validation: (rule) => rule.max(4),
    }),
    defineField({
      name: 'openToRoles',
      title: 'Open to roles',
      type: 'boolean',
      group: 'availability',
      description: 'Shows the "Open to roles" badge in the header and hero.',
      initialValue: false,
    }),
    defineField({
      name: 'rolesWanted',
      title: 'Roles wanted',
      type: 'array',
      group: 'availability',
      description: 'e.g. DevOps, Cloud, SRE. Press Enter after each.',
      of: [defineArrayMember({ type: 'string' })],
      options: { layout: 'tags' },
      validation: (rule) => rule.unique(),
    }),
    defineField({
      name: 'workPreference',
      title: 'Where',
      type: 'string',
      group: 'availability',
      description: 'Where you want to work, e.g. "Mumbai, elsewhere in India, or remote".',
    }),
    defineField({
      name: 'availability',
      type: 'string',
      group: 'availability',
      description: 'Notice period or start date. Leave empty to hide.',
    }),
    defineField({
      name: 'email',
      type: 'string',
      group: 'contact',
      validation: (rule) => rule.email(),
    }),
    defineField({
      name: 'linkedinUrl',
      title: 'LinkedIn URL',
      type: 'url',
      group: 'contact',
      validation: (rule) => rule.uri({ scheme: ['https'] }),
    }),
    defineField({
      name: 'githubUrl',
      title: 'GitHub URL',
      type: 'url',
      group: 'contact',
      validation: (rule) => rule.uri({ scheme: ['https'] }),
    }),
    defineField({
      name: 'socials',
      title: 'Other links',
      type: 'array',
      group: 'contact',
      description: 'Any other profiles, shown after LinkedIn and GitHub.',
      of: [defineArrayMember({ type: 'socialLink' })],
    }),
    defineField({
      name: 'resumeFile',
      title: 'Résumé PDF',
      type: 'file',
      group: 'contact',
      description: 'Upload a new PDF to replace the download on the Résumé page.',
      options: { accept: 'application/pdf' },
    }),
    defineField({
      name: 'seo',
      title: 'Default SEO',
      type: 'seo',
      group: 'seo',
      description: 'Used by every page that has no SEO of its own.',
    }),
  ],
  preview: { prepare: () => ({ title: 'Site settings' }) },
});
